"""Regenerate or check ``classbeat/db/queue_digests.py`` (ADR 0005 section 3).

The expected ``md5(pg_get_functiondef(oid))`` of each queue function depends on the exact text
of ``docker/postgres/queue/20-queue.sql`` and on how the pinned Postgres image renders it; that
of the two M5 guard trigger functions on migration ``0007_tiers``. Run it against a database
migrated to head where ``20-queue.sql`` has run (as the test superuser):

    uv run python tests/queue_digests.py --check   # CI: fails (with a diff) when it is stale
    uv run python tests/queue_digests.py --write   # after changing 20-queue.sql or a trigger

A guard trigger's digest is also written into ``20-queue.sql`` (its queue check refuses any other
body); ``tests/test_queue_guard_triggers.py`` fails when the two disagree.

It reads ``CLASSBEAT_TEST_DATABASE_URL``. Use the Postgres image compose pins (``postgres:17.11``).
"""

import difflib
import os
import sys
from pathlib import Path

from sqlalchemy import create_engine, text

TARGET = Path(__file__).resolve().parent.parent / "src" / "classbeat" / "db" / "queue_digests.py"
NAMES = ("queue_claim", "queue_reap", "queue_expire", "queue_unsettled", "queue_stats")
# The two M5 guard trigger functions (ADR 0011 section 1), made by migration 0007 as the owner:
# the only other user code the queue check admits, pinned the same way (and in 20-queue.sql).
HOOK_NAMES = ("credit_ledger_guard", "admin_audit_guard")
HEADER = '''"""Expected md5(pg_get_functiondef(oid)) of each job queue function (ADR 0005 s. 3).

Generated by ``tests/queue_digests.py --write`` from docker/postgres/queue/20-queue.sql on the
pinned Postgres image; CI regenerates it and fails when it is stale. Do not edit by hand.
"""

QUEUE_DIGESTS: dict[str, str] = {
'''
HOOK_HEADER = """}
# The M5 guard trigger functions (migration 0007), from the migrated database. The same digests
# are written into the queue check of docker/postgres/queue/20-queue.sql.
GUARD_TRIGGER_DIGESTS: dict[str, str] = {
"""


def digests(url: str, names: tuple[str, ...] = NAMES) -> dict[str, str]:
    engine = create_engine(url)
    try:
        with engine.connect() as connection:
            rows = connection.execute(
                text(
                    "SELECT p.proname, md5(pg_get_functiondef(p.oid)) FROM pg_proc p "
                    "JOIN pg_namespace n ON n.oid = p.pronamespace "
                    "WHERE n.nspname = 'public' AND p.proname = ANY(:names)"
                ),
                {"names": list(names)},
            ).all()
    finally:
        engine.dispose()
    found = {str(name): str(digest) for name, digest in rows}
    if sorted(found) != sorted(names) or len(rows) != len(names):
        raise SystemExit(
            "each queue and guard trigger function must exist exactly once; "
            "migrate to head and run 20-queue.sql first"
        )
    return found


def render(found: dict[str, str], hooks: dict[str, str]) -> str:
    return (
        HEADER
        + "".join(f'    "{name}": "{found[name]}",\n' for name in NAMES)
        + HOOK_HEADER
        + "".join(f'    "{name}": "{hooks[name]}",\n' for name in HOOK_NAMES)
        + "}\n"
    )


def main(argv: list[str]) -> int:
    if len(argv) != 1 or argv[0] not in ("--check", "--write"):
        print(__doc__)
        return 2
    url = os.environ.get("CLASSBEAT_TEST_DATABASE_URL")
    if not url:
        print("CLASSBEAT_TEST_DATABASE_URL is not set", file=sys.stderr)
        return 2
    wanted = render(digests(url), digests(url, HOOK_NAMES))
    if argv[0] == "--write":
        TARGET.write_text(wanted, encoding="utf-8", newline="\n")
        print(f"wrote {TARGET.name}")
        return 0
    current = TARGET.read_text(encoding="utf-8")
    if current == wanted:
        print("queue_digests.py is up to date")
        return 0
    sys.stdout.writelines(
        difflib.unified_diff(
            current.splitlines(keepends=True),
            wanted.splitlines(keepends=True),
            "queue_digests.py (committed)",
            "queue_digests.py (regenerated)",
        )
    )
    print("queue_digests.py is stale: run `uv run python tests/queue_digests.py --write`")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
